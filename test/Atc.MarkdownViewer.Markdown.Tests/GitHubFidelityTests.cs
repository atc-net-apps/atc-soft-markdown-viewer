namespace Atc.MarkdownViewer.Markdown.Tests;

/// <summary>
/// How close Markdig (our renderer) is to GitHub's renderer (cmark-gfm), measured against the expected HTML
/// in the GFM spec. Known differences are listed in <c>Fixtures/spec/markdig-vs-github.txt</c>; the test
/// fails only when a new difference appears (for example after a Markdig upgrade). Run with
/// <c>UPDATE_SNAPSHOTS=1</c> to rewrite the list, then review the diff.
/// </summary>
public sealed partial class GitHubFidelityTests
{
    private const string KnownDifferencesFile = "markdig-vs-github.txt";

    [Fact]
    public void MarkdigDifferencesFromGitHub_AreAllKnown()
    {
        // Arrange
        var examples = GfmSpecExample.Load();
        var path = Path.Combine(FixtureFiles.SourceSpecDirectory, KnownDifferencesFile);

        // Act
        var differences = examples
            .Where(e => !string.Equals(Normalize(Markdig.Markdown.ToHtml(e.Markdown, MarkdownPipelineFactory.Default)), Normalize(e.ExpectedHtml), StringComparison.Ordinal))
            .ToList();

        // Assert
        var report = BuildReport(examples.Count, differences);
        if (Environment.GetEnvironmentVariable("UPDATE_SNAPSHOTS") == "1")
        {
            File.WriteAllText(path, report);
            return;
        }

        var known = File.ReadAllLines(path)
            .Where(l => l.StartsWith('#') && char.IsDigit(l[1]))
            .Select(l => int.Parse(l[1..l.IndexOf(' ', StringComparison.Ordinal)], CultureInfo.InvariantCulture))
            .ToHashSet();
        differences.Where(d => !known.Contains(d.Number)).Select(d => d.ToString()).Should().BeEmpty("these examples newly differ from GitHub");
    }

    /// <summary>
    /// Removes differences that do not change what the browser shows: heading ids (GitHub adds them too, via
    /// its own anchor mechanism), table alignment spelled as <c>style</c> instead of <c>align</c>, task-list
    /// classes and checkbox attribute order, attribute spelling of booleans, self-closing slashes and
    /// whitespace between tags.
    /// </summary>
    private static string Normalize(string html)
    {
        var result = HeadingId().Replace(html, "<h${level}");
        result = TextAlign().Replace(result, "align=\"${align}\"");
        result = TaskListClass().Replace(result, string.Empty);
        result = CheckedCheckbox().Replace(result, "<input checked>");
        result = Checkbox().Replace(result, "<input>");
        result = BooleanAttribute().Replace(result, "${name}=\"\"");
        result = SelfClosing().Replace(result, ">");
        result = BetweenTags().Replace(result, "><");
        return result.Trim();
    }

    private static string BuildReport(
        int total,
        List<GfmSpecExample> differences)
    {
        var sb = new StringBuilder()
            .Append("Markdig compared with GitHub (cmark-gfm) on the GFM spec examples.\n")
            .Append("Generated by GitHubFidelityTests; rewrite with UPDATE_SNAPSHOTS=1.\n")
            .Append(CultureInfo.InvariantCulture, $"Matching: {total - differences.Count} of {total}. Differing: {differences.Count}.\n\n")
            .Append("By section:\n");
        foreach (var group in differences.GroupBy(d => d.Section, StringComparer.Ordinal).OrderByDescending(g => g.Count()))
        {
            sb.Append(CultureInfo.InvariantCulture, $"  {group.Key}: {group.Count()}\n");
        }

        sb.Append("\nExamples:\n");
        foreach (var difference in differences)
        {
            sb.Append(difference).Append('\n');
        }

        return sb.ToString();
    }

    [GeneratedRegex(@"<h(?<level>[1-6]) id=""[^""]*""", RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 5000)]
    private static partial Regex HeadingId();

    [GeneratedRegex(@"style=""text-align: (?<align>left|center|right);""", RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 5000)]
    private static partial Regex TextAlign();

    [GeneratedRegex(@" class=""(?:contains-task-list|task-list-item)""", RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 5000)]
    private static partial Regex TaskListClass();

    [GeneratedRegex(@"<input(?=[^>]*type=""checkbox"")(?=[^>]*checked)[^>]*>", RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 5000)]
    private static partial Regex CheckedCheckbox();

    [GeneratedRegex(@"<input(?=[^>]*type=""checkbox"")[^>]*>", RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 5000)]
    private static partial Regex Checkbox();

    [GeneratedRegex(@"(?<name>disabled|checked)=""\k<name>""", RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 5000)]
    private static partial Regex BooleanAttribute();

    [GeneratedRegex(@"\s*/>", RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 5000)]
    private static partial Regex SelfClosing();

    [GeneratedRegex(@">\s+<", RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 5000)]
    private static partial Regex BetweenTags();
}